# build.ps1 - compile the four ZOMBIE executables and write evidence\build.txt + evidence\imports.txt
#
#   powershell -ExecutionPolicy Bypass -File build.ps1
#
# Layout: this script lives in labs\06-zombie-protocol\src\; executables go to
# src\bin\ (git-ignored) and evidence lands in labs\06-zombie-protocol\evidence\.
#
# ASCII only on purpose: Windows PowerShell 5.1 mis-reads UTF-8 without BOM,
# and the evidence files must stay copy-pasteable. Chinese notes live in README.md.
$ErrorActionPreference = 'Stop'

$srcDir = Split-Path -Parent $MyInvocation.MyCommand.Path
$root = Split-Path -Parent $srcDir          # labs\06-zombie-protocol
Set-Location $srcDir

$binDir = Join-Path $srcDir 'bin'
$evDir = Join-Path $root 'evidence'
New-Item -ItemType Directory -Force -Path $binDir, $evDir | Out-Null

$gcc = Get-Command gcc -ErrorAction SilentlyContinue
$objdump = Get-Command objdump -ErrorAction SilentlyContinue
if (-not $gcc) { throw 'gcc not found in PATH (expected C:\mingw64\bin\gcc.exe)' }
if (-not $objdump) { throw 'objdump not found in PATH (expected C:\mingw64\bin\objdump.exe)' }

# ---------------------------------------------------------------- build.txt
$buildLog = New-Object System.Collections.Generic.List[string]
function Add-BuildLine([string]$text) { $buildLog.Add($text) }

Add-BuildLine '### evidence/build.txt - generated by build.ps1 (raw gcc output, not edited)'
Add-BuildLine ('### cwd   : ' + (Get-Location).Path)
Add-BuildLine ('### time  : ' + (Get-Date -Format 'yyyy-MM-dd HH:mm:ss'))
Add-BuildLine ('### ' + (& gcc --version | Select-Object -First 1))
Add-BuildLine ('### ' + (& objdump --version | Select-Object -First 1))
Add-BuildLine ''

$targets = @(
    @{ Out = 'zombie_srv_O0.exe';  Src = 'zombie_srv.c'; Flags = @('-O0', '-g'); What = 'server, debug build (readable in Ghidra/x64dbg)' },
    @{ Out = 'zombie_srv_O2s.exe'; Src = 'zombie_srv.c'; Flags = @('-O2', '-s'); What = 'server, real-game shape (optimized + stripped)' },
    @{ Out = 'zombie_cli_O0.exe';  Src = 'zombie_cli.c'; Flags = @('-O0', '-g'); What = 'client, debug build' },
    @{ Out = 'zombie_cli_O2s.exe'; Src = 'zombie_cli.c'; Flags = @('-O2', '-s'); What = 'client, real-game shape' }
)

foreach ($t in $targets) {
    $outPath = Join-Path $binDir $t.Out
    $gargs = @() + $t.Flags + @('-Wall', '-Wextra', '-o', $outPath, $t.Src, '-lws2_32')
    Add-BuildLine ('### ' + $t.What)
    Add-BuildLine ('> gcc ' + ($gargs -join ' '))
    $text = & gcc @gargs 2>&1
    $code = $LASTEXITCODE
    if ($text) {
        foreach ($line in $text) { Add-BuildLine ('  ' + [string]$line) }
    }
    Add-BuildLine ('  exit code = ' + $code)
    if ($code -ne 0) {
        [IO.File]::WriteAllLines((Join-Path $evDir 'build.txt'), $buildLog, (New-Object System.Text.UTF8Encoding($false)))
        throw "gcc failed for $($t.Out) (exit $code)"
    }
    Add-BuildLine ''
}

Add-BuildLine '### file sizes (Get-ChildItem bin\*.exe | Sort-Object Name)'
Add-BuildLine ''
foreach ($f in (Get-ChildItem (Join-Path $binDir '*.exe') | Sort-Object Name)) {
    Add-BuildLine ('{0,-22} {1,8} bytes {2,7:N1} KB' -f $f.Name, $f.Length, ($f.Length / 1KB))
}
Add-BuildLine ''
Add-BuildLine '### -O0 -g keeps the frame layout and every symbol; -O2 -s strips the symbol table.'
Add-BuildLine '### That size gap is exactly why the -O2 -s pair is the one you reverse.'

[IO.File]::WriteAllLines((Join-Path $evDir 'build.txt'), $buildLog, (New-Object System.Text.UTF8Encoding($false)))
Write-Host ('build.ps1: wrote ' + (Join-Path $evDir 'build.txt'))

# -------------------------------------------------------------- imports.txt
$imp = New-Object System.Collections.Generic.List[string]
function Add-ImpLine([string]$text) { $imp.Add($text) }

Add-ImpLine '### evidence/imports.txt - generated by build.ps1'
Add-ImpLine '### Source: objdump -p <exe>. Lines are copied raw from objdump output.'
Add-ImpLine '### Point: socket()/send()/recv() are NOT compiled into these exes. They are'
Add-ImpLine '### imports from WS2_32.dll, resolved by the loader when the process starts.'
Add-ImpLine ''

foreach ($name in @('zombie_srv_O2s.exe', 'zombie_cli_O2s.exe', 'zombie_srv_O0.exe', 'zombie_cli_O0.exe')) {
    $path = Join-Path $binDir $name
    $all = & objdump -p $path 2>&1
    Add-ImpLine ('===== ' + $name + ' =====')
    Add-ImpLine ('> objdump -p ' + $name + ' | findstr "DLL Name"')
    foreach ($n in ($all | Where-Object { $_ -match 'DLL Name:' })) {
        Add-ImpLine ('  ' + ([string]$n).Trim())
    }
    Add-ImpLine ''

    Add-ImpLine ('> objdump -p ' + $name + '   (the WS2_32.dll import block, raw)')
    $startIdx = -1
    for ($i = 0; $i -lt $all.Count; $i++) {
        if ($all[$i] -match 'DLL Name:\s*WS2_32') { $startIdx = $i; break }
    }
    if ($startIdx -lt 0) {
        Add-ImpLine '  (no WS2_32.dll import found)'
    } else {
        # the block is: "DLL Name: ...", a "vma:" header line, the member lines,
        # then a blank line -> stop there instead of running into the next table
        $endIdx = $all.Count
        for ($i = $startIdx + 1; $i -lt $all.Count; $i++) {
            if (([string]$all[$i]).Trim() -eq '') { $endIdx = $i; break }
        }
        for ($i = $startIdx; $i -lt $endIdx; $i++) { Add-ImpLine ('  ' + [string]$all[$i]) }
        $count = 0
        for ($i = $startIdx + 2; $i -lt $endIdx; $i++) {
            if ($all[$i] -match '<none>') { $count++ }
        }
        Add-ImpLine ('  -> ' + $count + ' functions imported from WS2_32.dll')
    }
    Add-ImpLine ''
}

[IO.File]::WriteAllLines((Join-Path $evDir 'imports.txt'), $imp, (New-Object System.Text.UTF8Encoding($false)))
Write-Host ('build.ps1: wrote ' + (Join-Path $evDir 'imports.txt'))
